# За счёт алгоритма сначала высчитываем все возможные проходы коня, 
# запоминая расстояние от начальной точки, 
# а потом выводим значение расстояния на финишной клетке 
# и по массиву предков возвращаемся до изначальной,
# преобразуя все значения в координаты
from collections import deque

# Переводим координаты клетки (x, y) в один номер вершины
# (x - 1) * n — количество клеток перед строкой x
# (y - 1) — позиция клетки внутри строки
def number(x, y):
    return (x - 1) * n + (y - 1)

# Переводим номер вершины обратно в координаты клетки
# v // n + 1 — номер строки
# v % n + 1 — номер столбца
def coords(v):
    return v // n + 1, v % n + 1

n = int(input())
x1, y1 = map(int, input().split())
x2, y2 = map(int, input().split())

# Все 8 возможных ходов шахматного коня
moves = [
    (2, 1), (2, -1),
    (-2, 1), (-2, -1),
    (1, 2), (1, -2),
    (-1, 2), (-1, -2)
]

# graph[v] содерж номера клеток,
# в которые конь может перейти из клетки v
graph = [[] for _ in range(n * n)]

for x in range(1, n + 1):
    for y in range(1, n + 1):
        v = number(x, y)

        for dx, dy in moves:
            nx = x + dx
            ny = y + dy
            # Проверяем, не выходит ли конь за границы доски
            if 1 <= nx <= n and 1 <= ny <= n:
                graph[v].append(number(nx, ny))


s = number(x1, y1)
finish = number(x2, y2)

# массив расстояний до каждой клетки
dist = [-1] * (n * n)
# pred[v] — номер клетки, из которой мы пришли в v
pred = [-1] * (n * n)

# До стартовой клетки требуется 0 ходов
dist[s] = 0
# очередь со стартовой вершиной
q = deque([s])

while q:
    node = q.popleft()

    for neighbor in graph[node]:
        # Проверяем, посещали ли соседнюю клетку
        if dist[neighbor] == -1:
            dist[neighbor] = dist[node] + 1
            pred[neighbor] = node
            # Добавляем новую клетку в очередь
            q.append(neighbor)

# список для пути
path = []

ver = finish

# пока не достигнем предшественника стартовой клетки
# добавляем текущую клетку в путь
while ver != -1:
    path.append(ver)
    # Переходим к клетке, из которой пришли в текущую
    ver = pred[ver]

path.reverse()

# Выводим минимальное количество ходов коня
print(dist[finish])

for v in path:
    print(*coords(v))
