from collections import deque

# a = [1, 3, 2, 4, 5, 3, 1], k = 3

# i=0, a[0]=1:
#   dq = [0]
#   i < 2, не выводим

# i=1, a[1]=3:
#   a[1]=3 > a[0]=1 -> не удаляем
#   dq = [0, 1]
#   i < 2, не выводим

# i=2, a[2]=2:
#   dq[0] <= 2 - 3 -> идём дальше
#   a[dq[-1]]=3 >= a[i]=2 -> удаляем индекс с конца (1) dq=[0]
#   a[dq[-1]]=1 >= a[i]=2 -> не удаляем
#   dq = [0, 2]
#   i >= 2 -> выводим a[dq[0]] = a[0] = 1 

# i=3, a[3]=4:
#   dq[0]=0 <= 3-3=0 -> удаляем индекс c начала стека (0) dq = [2]
#   dq[0]=2 <= 3-3=0 -> идём дальше
#   a[dq[-1]]=2 >= a[3]=4 -> не удаляем
#   dq = [2, 3]
#   i >= 2 -> выводим a[dq[0]] = a[2] = 2 

# i=4, a[4]=5:
#   dq[0]=2 > 4-3=1 -> не удаляем
#   a[4]=5 > a[3]=4 -> не удаляем
#   dq = [2, 3, 4]
#   выводим a[dq[0]] = a[2] = 2 

# i=5, a[5]=3:
#   dq[0]=2 <= 5-3=2 -> удаляем индекс 2
#   a[5]=3 < a[4]=5 -> удаляем индекс 4
#   a[5]=3 < a[3]=4 -> удаляем индекс 3
#   dq = [5]
#   выводим a[dq[0]] = a[5] = 3 

# i=6, a[6]=1:
#   dq[0]=5 > 6-3=3 -> не удаляем
#   a[6]=1 < a[5]=3 -> удаляем индекс 5
#   dq = [6]
#   выводим a[dq[0]] = a[6] = 1 

# Результат: 1, 2, 2, 3, 1 

n, k = map(int, input().split())
# 1 3 2 4 5 3 1
a = list(map(int, input().split()))

# храним ИНДЕКСЫ элементов в порядке возрастания значений
dq = deque()  

for i in range(n):
    # 1. Удаляем элементы с начала дека, которые вышли из окна
    #    (их индекс слишком далеко от текущего)
    # i = 4, k = 3
    # Окно: [2, 4, 5] (индексы 2, 3, 4)
    # Граница: i - k = 4 - 3 = 1
    # Если в деке есть индекс 0 или 1 → удаляем (они вышли из окна)
    while dq and dq[0] <= i - k:
        dq.popleft()
    
    # 2. Удаляем с конца дека все элементы >= текущего
    #    (они бесполезны: текущий меньше и новее)
    # i = 0: dq = [0] (значение 1)
    # i = 1: a[1]=3 > a[0]=1 -> не удаляем, dq = [0, 1]
    # i = 2: a[2]=2 < a[1]=3 -> удаляем индекс 1!
    #        a[2]=2 > a[0]=1 -> не удаляем
    #        dq = [0, 2]
    while dq and a[dq[-1]] >= a[i]:
        dq.pop()
    
    # 3. Добавляем текущий элемент в конец дека
    dq.append(i)
    
    # 4. Выводим минимум, когда набрали полное окно
    if i >= k - 1:
        # первый в деке — минимум
        print(a[dq[0]])  
