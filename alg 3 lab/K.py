n = int(input())
a = list(map(int, input().split()))

# Строим префиксные суммы для быстрого вычисления суммы на любом отрезке
# prefix[i] = сумма первых i элементов массива a
# Пример: a = [3, 1, 6, 4, 5, 2]
#         prefix = [0, 3, 4, 10, 14, 19, 21]
# Сумма отрезка [l, r] = prefix[r+1] - prefix[l]
prefix = [0] * (n + 1)
for i in range(n):
    prefix[i + 1] = prefix[i] + a[i]

# Монотонный стек для хранения индексов элементов
# В стеке индексы идут в порядке возрастания их значений
stack = []

# Лучшая найденная значимость (инициализируем -1, т.к. все значимости >= 0)
res = -1

# Границы лучшего отрезка (в 1-индексации, как требует задача)
resl = 1
resr = 1

# Проходим по всем элементам + один фиктивный шаг в конце
for i in range(n + 1):
    # Если это реальный элемент (i < n), берем его значение
    # Если i = n (фиктивный шаг), подставляем -1 для очистки стека
    if i < n:
        cur_val = a[i]
    else:
        cur_val = -1

    # Пока стек не пуст и элемент на вершине стека >= текущего
    # (текущий элемент "ломает" монотонность)
    while len(stack) > 0 and a[stack[-1]] >= cur_val:
        # Вынимаем элемент из стека - это кандидат на минимум отрезка
        b = a[stack.pop()]

        # Находим левую границу отрезка:
        # Если стек не пуст, то новый верх - это первый элемент слева,
        # который меньше b. Иначе отрезок начинается с 0.
        if len(stack) > 0:
            l = stack[-1]
        else:
            l = -1

        # Вычисляем сумму отрезка [l+1, i-1] через префиксные суммы
        # l+1 - начало отрезка (после элемента, который меньше b)
        # i-1 - конец отрезка (перед текущим элементом)
        c = prefix[i] - prefix[l + 1]

        # Вычисляем значимость: минимум * сумма
        # Если она лучше текущей лучшей - обновляем ответ
        if b * c > res:
            res = b * c
            # Переводим границы в 1-индексацию:
            # l+1 (0-индексация) -> l+2 (1-индексация)
            resl = l + 2
            # i-1 (0-индексация) -> i (1-индексация)
            resr = i

    # Добавляем текущий индекс в стек (для фиктивного элемента i=n тоже)
    stack.append(i)

# Выводим максимальную значимость
print(res)

# Выводим границы лучшего отрезка (в 1-индексации)
print(resl, resr)
