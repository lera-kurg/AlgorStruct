# Функция проверки: можно ли получить k отрезков длины 'length'
def ok(length):
    # Счётчик количества отрезков, которые можно получить
    count = 0
    # Проходим по каждому проводу
    for wire in wires:
        # Из одного провода длины 'wire' можно получить 'wire // length' отрезков
        # Например, из провода 802 см можно получить 802 // 200 = 4 отрезка по 200 см
        count += wire // length
    # Возвращаем True, если получили достаточно отрезков (>= k)
    return count >= k


# количество проводов, сколько отрезков нужно получить
n, k = map(int, input().split())

# Создаём список для хранения длин проводов
wires = [int(input()) for _ in range(n)]

# left = 0 - заведомо неподходящая длина (деление на 0 невозможно, но это нижняя граница)
left = 0
# right = max(wires) + 1 - заведомо большая длина (больше самого длинного провода)
right = max(wires) + 1


while right - left > 1:
    mid = (left + right) // 2

    # Проверяем, можно ли получить k отрезков длины mid
    if ok(mid):
        left = mid
    else:
        right = mid

# left - это наибольшее значение, при котором ok() вернул True
print(left)